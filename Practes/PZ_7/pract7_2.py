# Даны строки S, S1 и S2. Заменить в строке S последнее вхождение строки S1 на строку
# S2.

s = "играл на гитаре"
s1 = "проиграл"
s2 = "мистер коконут мери крисмас ис фор ю"
s42 = 0

print(f"s = {s},\ns1 = {s1},\ns2 = {s2}")

for i in range(len(s)):
    if s[i] in s1:
        s42 = i

print(f"{s[:s42]}{s2}{s[s42:]}")